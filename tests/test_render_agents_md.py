import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCRIPT = REPO / "scripts" / "render_agents_md.py"
MARKER = "<!-- generated by ai-config apply.sh from claude/CLAUDE.md and claude/rules; edit those, not this file -->"
CLAUDE_MD = "# Global\n\nRules — with § and `code`.\n"
OPEN = "<!-- claude-only -->"
CLOSE = "<!-- /claude-only -->"


class RenderAgentsMdTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(dir=os.environ.get("TMPDIR"))
        self.addCleanup(self.tmp.cleanup)
        self.dir = Path(self.tmp.name)
        self.claude_md = self.dir / "CLAUDE.md"
        self.claude_md.write_text(CLAUDE_MD, encoding="utf-8")
        self.rules = self.dir / "rules"
        self.rules.mkdir()

    def rule(self, name, text):
        (self.rules / name).write_text(text, encoding="utf-8")

    def render(self, claude_md=None):
        return subprocess.run(
            [sys.executable, str(SCRIPT), "--claude-md", str(claude_md or self.claude_md), "--rules-dir", str(self.rules)],
            capture_output=True,
        )

    def assert_error(self, proc):
        self.assertEqual(proc.returncode, 1)
        self.assertTrue(proc.stderr.startswith(b"ERROR: "), proc.stderr)
        self.assertEqual(proc.stdout, b"")

    def assert_error_at(self, proc, path, line):
        self.assert_error(proc)
        self.assertTrue(proc.stderr.startswith(f"ERROR: {path}:{line}: ".encode("utf-8")), proc.stderr)

    def test_marker_blank_line_claude_md_verbatim_then_rule_bodies_in_name_order(self):
        self.rule("b-style.md", "# Style\n\nBody b.\n")
        self.rule("a-git.md", "# Git\n\nBody a.\n")
        self.rule("notes.txt", "not a rule\n")
        proc = self.render()
        self.assertEqual(proc.returncode, 0, proc.stderr)
        expected = MARKER + "\n\n" + CLAUDE_MD + "\n# Git\n\nBody a.\n" + "\n# Style\n\nBody b.\n"
        self.assertEqual(proc.stdout, expected.encode("utf-8"))

    def test_missing_claude_md_exits_1_with_error(self):
        self.assert_error(self.render(claude_md=self.dir / "absent.md"))

    def test_claude_only_block_is_dropped_and_the_text_before_and_after_it_is_kept(self):
        self.claude_md.write_text(f"# Global\n\nbefore\n{OPEN}\nclaude only\n{CLOSE}\nafter\n", encoding="utf-8")
        proc = self.render()
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(proc.stdout, (MARKER + "\n\n# Global\n\nbefore\nafter\n").encode("utf-8"))

    def test_open_fence_without_a_close_exits_1_with_error_at_its_line_and_empty_stdout(self):
        self.claude_md.write_text(f"before\n{OPEN}\nclaude only\n", encoding="utf-8")
        self.assert_error_at(self.render(), self.claude_md, 2)


if __name__ == "__main__":
    unittest.main()
